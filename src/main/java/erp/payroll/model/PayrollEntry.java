package erp.payroll.model;

/**
 * [급여관리] 사원별 지급 및 공제 항목 상세 내역 Model DB 테이블: PAYROLL_ENTRY
 */
// 급여상세내역 정보를 보관하고 관련 기능에서 사용할 수 있도록 제공한다.
// 給与明細情報を保持し、関連機能から利用できるように提供する。
public class PayrollEntry {

	// [연결 정보]
	// データベースの主キー・外部キー・基本属性を保持し、永続化対象を識別する。
	private int payrollEntryId; // 지급·공제 상세내역 식별 번호 (PK)
	private int payrollEmployeeId; // 사원별 급여결과 식별 번호 (FK)

	// [지급·공제 항목]
	// ※ 하나는 값이 있고, 다른 하나는 반드시 NULL이어야 하는 상호 배타적 구조
	// 未入力値とNULLを区別して正規化し、制約違反や不要な値の保存を防止する。
	private Integer payItemId; // 지급행일 경우 지급항목 식별 번호 (선택적 FK)
	private Integer deductItemId; // 공제행일 경우 공제항목 식별 번호 (선택적 FK)

	// [항목별 금액]
	// 支給額・控除額・期間値を業務基準に従って計算し、合計と最終金額へ反映する。
	private long amount; // 지급액 또는 공제액

	// 전달받은 값으로 급여상세내역 객체의 초기 상태를 구성한다.
	// 생성 시 전달된 필수값을 각 필드에 보관하여 이후 조회와 화면 출력에서 재사용한다.
	// 受け取った値で給与明細オブジェクトの初期状態を構成する。
	// 生成時に受け取った必須値を各フィールドへ保持し、後続の照会と画面表示で再利用する。
	public PayrollEntry() {
	}

	// [비즈니스 로직] 지급 항목인지 공제 항목인지 스스로 판단
	// 지급상세내역 조건의 충족 여부를 확인하여 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
	// 支給明細条件を満たしているか確認して返す。
	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public boolean isPaymentEntry() {
		return this.payItemId != null && this.payItemId > 0;
	}

	// 공제상세내역 조건의 충족 여부를 확인하여 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
	// 控除明細条件を満たしているか確認して返す。
	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public boolean isDeductEntry() {
		return this.deductItemId != null && this.deductItemId > 0;
	}

	// Getter & Setter
	// 급여상세내역 객체에 저장된 급여상세내역식별번호 값을 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
	// 給与明細オブジェクトに保存された給与明細識別番号の値を返す。
	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public int getPayrollEntryId() {
		return payrollEntryId;
	}

	// 전달받은 급여상세내역식별번호 값을 급여상세내역 객체에 저장한다.
	// 요청값이나 조회 결과로 전달된 값을 대응하는 필드에 반영하여 객체의 현재 상태를 갱신한다.
	// 受け取った給与明細識別番号の値を給与明細オブジェクトに保存する。
	// リクエスト値または照会結果として渡された値を対応フィールドへ反映し、オブジェクトの現在状態を更新する。
	public void setPayrollEntryId(int payrollEntryId) {
		this.payrollEntryId = payrollEntryId;
	}

	// 급여상세내역 객체에 저장된 급여사원식별번호 값을 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
	// 給与明細オブジェクトに保存された給与社員識別番号の値を返す。
	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public int getPayrollEmployeeId() {
		return payrollEmployeeId;
	}

	// 전달받은 급여사원식별번호 값을 급여상세내역 객체에 저장한다.
	// 요청값이나 조회 결과로 전달된 값을 대응하는 필드에 반영하여 객체의 현재 상태를 갱신한다.
	// 受け取った給与社員識別番号の値を給与明細オブジェクトに保存する。
	// リクエスト値または照会結果として渡された値を対応フィールドへ反映し、オブジェクトの現在状態を更新する。
	public void setPayrollEmployeeId(int payrollEmployeeId) {
		this.payrollEmployeeId = payrollEmployeeId;
	}

	// 급여상세내역 객체에 저장된 지급항목식별번호 값을 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
	// 給与明細オブジェクトに保存された支給項目識別番号の値を返す。
	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public Integer getPayItemId() {
		return payItemId;
	}

	// 전달받은 지급항목식별번호 값을 급여상세내역 객체에 저장한다.
	// 요청값이나 조회 결과로 전달된 값을 대응하는 필드에 반영하여 객체의 현재 상태를 갱신한다.
	// 受け取った支給項目識別番号の値を給与明細オブジェクトに保存する。
	// リクエスト値または照会結果として渡された値を対応フィールドへ反映し、オブジェクトの現在状態を更新する。
	public void setPayItemId(Integer payItemId) {
		this.payItemId = payItemId;
	}

	// 급여상세내역 객체에 저장된 공제항목식별번호 값을 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
	// 給与明細オブジェクトに保存された控除項目識別番号の値を返す。
	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public Integer getDeductItemId() {
		return deductItemId;
	}

	// 전달받은 공제항목식별번호 값을 급여상세내역 객체에 저장한다.
	// 요청값이나 조회 결과로 전달된 값을 대응하는 필드에 반영하여 객체의 현재 상태를 갱신한다.
	// 受け取った控除項目識別番号の値を給与明細オブジェクトに保存する。
	// リクエスト値または照会結果として渡された値を対応フィールドへ反映し、オブジェクトの現在状態を更新する。
	public void setDeductItemId(Integer deductItemId) {
		this.deductItemId = deductItemId;
	}

	// 급여상세내역 객체에 저장된 금액 값을 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
	// 給与明細オブジェクトに保存された金額の値を返す。
	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public long getAmount() {
		return amount;
	}

	// 전달받은 금액 값을 급여상세내역 객체에 저장한다.
	// 요청값이나 조회 결과로 전달된 값을 대응하는 필드에 반영하여 객체의 현재 상태를 갱신한다.
	// 受け取った金額の値を給与明細オブジェクトに保存する。
	// リクエスト値または照会結果として渡された値を対応フィールドへ反映し、オブジェクトの現在状態を更新する。
	public void setAmount(long amount) {
		this.amount = amount;
	}
}
