	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public int getItemCode() {
		return itemCode;
	}

	// 전달받은 항목코드 값을 급여입력·관리항목 객체에 저장한다.
	// 요청값이나 조회 결과로 전달된 값을 대응하는 필드에 반영하여 객체의 현재 상태를 갱신한다.
	// 受け取った項目コードの値を給与入力・管理項目オブジェクトに保存する。
	// リクエスト値または照会結果として渡された値を対応フィールドへ反映し、オブジェクトの現在状態を更新する。
	public void setItemCode(int itemCode) {
		this.itemCode = itemCode;
	}

	// 급여입력·관리항목 객체에 저장된 항목명칭 값을 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
	// 給与入力・管理項目オブジェクトに保存された項目名称の値を返す。
	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public String getItemName() {
		return itemName;
	}

	// 전달받은 항목명칭 값을 급여입력·관리항목 객체에 저장한다.
	// 요청값이나 조회 결과로 전달된 값을 대응하는 필드에 반영하여 객체의 현재 상태를 갱신한다.
	// 受け取った項目名称の値を給与入力・管理項目オブジェクトに保存する。
	// リクエスト値または照会結果として渡された値を対応フィールドへ反映し、オブジェクトの現在状態を更新する。
	public void setItemName(String itemName) {
		this.itemName = itemName;
	}

	// 세금비과세 조건의 충족 여부를 확인하여 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
	// 税金非課税条件を満たしているか確認して返す。
	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public boolean isTaxFree() {
		return taxFree;
	}

	// 전달받은 세금비과세 값을 급여입력·관리항목 객체에 저장한다.
	// 요청값이나 조회 결과로 전달된 값을 대응하는 필드에 반영하여 객체의 현재 상태를 갱신한다.
	// 受け取った税金非課税の値を給与入力・管理項目オブジェクトに保存する。
	// リクエスト値または照会結果として渡された値を対応フィールドへ反映し、オブジェクトの現在状態を更新する。
	public void setTaxFree(boolean taxFree) {
		this.taxFree = taxFree;
	}

	// 급여입력·관리항목 객체에 저장된 계산방법 값을 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
	// 給与入力・管理項目オブジェクトに保存された計算方法の値を返す。
	// 保持しているフィールドを直接公開せず、アクセサーメソッドを通して必要な階層へ提供する。
	public String getCalculationMethod() {
		return calculationMethod;
	}

	// 전달받은 계산방법 값을 급여입력·관리항목 객체에 저장한다.
	// 요청값이나 조회 결과로 전달된 값을 대응하는 필드에 반영하여 객체의 현재 상태를 갱신한다.
	// 受け取った計算方法の値を給与入力・管理項目オブジェクトに保存する。
	// リクエスト値または照会結果として渡された値を対応フィールドへ反映し、オブジェクトの現在状態を更新する。
