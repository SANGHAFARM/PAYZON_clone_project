	private int itemCode;
	private String itemName;
	private boolean taxFree;
	private String calculationMethod;
	private long amount;

	// 급여입력·관리항목 객체에 저장된 항목코드 값을 반환한다.
	// 저장된 필드를 외부에 직접 노출하지 않고 접근 메서드를 통해 필요한 계층에 제공한다.
